const assert=require('node:assert/strict');
const S=require('../insights.js');
const near=(a,b)=>assert.ok(Math.abs(a-b)<1e-9,`${a} != ${b}`);
assert.deepEqual(S.ranks([3,1,1,2]),[4,1.5,1.5,3]);
near(S.spearman([1,2,3,4],[9,7,5,3]),-1);
assert.equal(S.correlation([1,1,1],[1,2,3]),null);
const day=i=>new Date(Date.UTC(2026,0,1+i)).toISOString().slice(0,10);
const make=(id,values)=>({id,history:Object.fromEntries(values.map((v,i)=>[day(i),v]))});
const weekly=Array.from({length:84},(_,i)=>i%7+1);
const confounded=S.pair(make('a',weekly),make('b',weekly.map(v=>v*3)),84,day(84),0);
near(confounded.raw,1); assert.equal(confounded.r,null);assert.match(confounded.reason,/variation/);
let seed=123;const random=()=>{seed=(seed*1664525+1013904223)>>>0;return seed/4294967296;};
const values=Array.from({length:90},()=>1+random()*8);
const next=[3,...values.slice(0,-1)];
const result=S.analyze([make('a',values),make('b',next)],90,day(90));
const forward=result.results.find(r=>r.a==='a'&&r.lag===1);
near(forward.raw,1);near(forward.r,1);assert.equal(forward.n,89);assert.ok(forward.stable);assert.ok(forward.q>=forward.p);assert.ok(forward.screened);
const sparse=S.pair(make('a',values.map((v,i)=>i<3?v:0)),make('b',values),90,day(90),0);
assert.match(sparse.reason,/active/);assert.equal(sparse.p,null);
const bounded=S.aligned(make('a',values),{id:'b',history:{[day(80)]:2,[day(90)]:99}},30,day(90),1);
assert.equal(bounded[0].yDate,day(80));assert.equal(bounded.at(-1).yDate,day(89));assert.equal(bounded.length,10);
assert.equal(S.aligned(make('a',values),{id:'b',history:{}},90,day(90)).length,0);
const corrected=S.correct([{p:0.01},{p:0.04},{p:0.03},{p:null}]);
near(corrected[0].q,.01*3*(1+1/2+1/3));near(corrected[1].q,.04*(1+1/2+1/3));assert.equal(corrected[3].q,undefined);
assert.equal(result.results.length,3);assert.equal(S.analyze([],90,day(90)).results.length,0);
const reversal=S.pair(make('a',values),make('b',values.map((v,i)=>i<45?v:10-v)),90,day(90),0);
assert.equal(reversal.stable,false);
console.log('PASS: ties, constants, weekday confounding, lag alignment, sparse data, complete-date boundaries, BY correction, empty data, changing relationships.');

